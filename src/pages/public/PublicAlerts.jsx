import { useEffect, useState } from 'react';
import { Bell, AlertTriangle } from 'lucide-react';
import RiskBadge from '../../components/common/RiskBadge';
import { alertService } from '../../services/alertService';
import { fmtDateTime } from '../../utils/formatters';

export default function PublicAlerts() {
  const [alerts, setAlerts] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  useEffect(() => {
    let cancelled = false;
    (async () => {
      try {
        const data = await alertService.active();
        const list = Array.isArray(data?.alerts) ? data.alerts : [];
        if (!cancelled) setAlerts(list);
      } catch (e) { if (!cancelled) setError(e); }
      finally { if (!cancelled) setLoading(false); }
    })();
    return () => { cancelled = true; };
  }, []);

  return (
    <div className="space-y-6">
      <section className="vn-panel p-6">
        <h1 className="text-xl font-semibold" style={{ color: 'var(--vn-primary)' }}>Active Alerts</h1>
        <p className="text-sm text-slate-600 mt-1">Current weather warnings for your region, reviewed by disaster management authorities.</p>
      </section>

      {loading && <section className="vn-panel p-6 text-sm text-slate-500">Loading alerts…</section>}

      {!loading && error && (
        <section className="vn-panel p-6" style={{ borderLeft: '4px solid var(--vn-red)' }}>
          <div className="flex items-start gap-3">
            <AlertTriangle size={18} style={{ color: 'var(--vn-red)' }} />
            <div>
              <div className="font-semibold text-slate-800">Could not load alerts</div>
              <p className="text-sm text-slate-600 mt-1">{error.message}</p>
            </div>
          </div>
        </section>
      )}

      {!loading && !error && alerts.length === 0 && (
        <section className="vn-panel p-8 text-center">
          <Bell size={28} className="mx-auto text-slate-400" />
          <p className="mt-3 text-sm text-slate-700 font-medium">No active alerts right now.</p>
          <p className="text-xs text-slate-500 mt-1">Alerts will appear here as soon as an authority issues one.</p>
        </section>
      )}

      {!loading && !error && alerts.length > 0 && (
        <div className="space-y-3">
          {alerts.map((a) => (
            <div key={a._id || a.alert_id || a.id} className="vn-panel p-5" style={{ borderLeft: '4px solid var(--vn-orange)' }}>
              <div className="flex items-center justify-between flex-wrap gap-2">
                <div className="flex items-center gap-3">
                  <RiskBadge risk={a.severity || a.risk} />
                  <span className="text-sm font-semibold text-slate-800">+{a.horizon_hours ?? a.hours}h forecast</span>
                </div>
                <span className="text-xs text-slate-500">{fmtDateTime(a.created_at)}</span>
              </div>
              <div className="mt-3 text-sm text-slate-700">
                Alert issued for grid cell <span className="vn-mono font-medium">Y{a.grid_y} · X{a.grid_x}</span>, probability <span className="vn-mono font-medium">{(a.probability ?? a.max_probability ?? 0).toFixed(4)}</span>.
              </div>
              <div className="mt-2 text-xs text-slate-500">Status: <strong>{a.status}</strong>. Follow official guidance from your district administration.</div>
            </div>
          ))}
        </div>
      )}

      <p className="text-xs text-slate-500">Alerts shown here are generated by the model and reviewed by disaster management officers. Always also check official IMD forecasts.</p>
    </div>
  );
}
